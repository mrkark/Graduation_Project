/**
 * Получить тайминги для конкретного шага ката Хэйан Шодан (1-based)
 */
export function getHeianShodanStepTiming(stepNumber) {
  const num = Number(stepNumber);
  const found = HEIAN_SHODAN_STEP_TIMINGS.find((s) => s.step === num);
  if (found) return found;
  if (num > 0 && num <= HEIAN_SHODAN_STEP_TIMINGS.length) {
    return HEIAN_SHODAN_STEP_TIMINGS[num - 1];
  }
  return HEIAN_SHODAN_STEP_TIMINGS[0];
}

