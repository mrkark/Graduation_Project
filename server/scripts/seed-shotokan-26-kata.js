async function seed() {
  console.log('🥋 Начало наполнения базы данных 26 каноническими Ката Шотокан…');

  // Получаем список существующих ката, чтобы не дублировать
  const existingList = await callProcedure('sp_Kata_List', {
    UserId: 1,
    UserRole: 'admin',
    Search: null,
    Difficulty: null,
    Style: null,
    Status: null,
    Sort: 'newest',
    Offset: 0,
    Limit: 100,
  });

  const existingTitles = new Set(existingList.map((k) => k.Title.trim().toLowerCase()));
  console.log(`Найдено существующих ката в БД: ${existingList.length}`);

  let createdCount = 0;

  for (const kata of SHOTOKAN_26_KATA) {
    const titleKey = kata.title.trim().toLowerCase();
    if (existingTitles.has(titleKey)) {
      console.log(`⏩ Пропускаем (уже есть): ${kata.title}`);
      continue;
    }

    try {
      const result = await callProcedure('sp_Kata_Create', {
        AuthorId: 1, // системный администратор admin
        Title: kata.title,
        Description: kata.description,
        Difficulty: kata.difficulty,
        Style: kata.style,
        VideoUrl: null,
        ThumbnailUrl: null,
        StepsJson: JSON.stringify(kata.steps),
      });

      const newId = result[0]?.Kata_ID;
      if (newId) {
        // Утверждаем ката, чтобы оно было видно всем пользователям
        await callProcedure('sp_Kata_SetStatus', {
          KataId: newId,
          Status: 'approved',
        });
        createdCount++;
        console.log(`✔ [${createdCount}/26] Создано и утверждено: #${newId} ${kata.title} (${kata.steps.length} шагов)`);
      }
    } catch (err) {
      console.error(`✘ Ошибка при создании ${kata.title}:`, err.message);
    }
  }

  console.log(`\n🎉 Наполнение завершено! Добавлено новых ката: ${createdCount}. Всего ката в БД: ${existingList.length + createdCount}`);
}

seed()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('Критическая ошибка:', err);
    process.exit(1);
  });
